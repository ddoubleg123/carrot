/** Channel label, replaced by the live category when Twitch or Kick names the current show. */
export function categoryFor(id: string, topic?: string | null, parent?: string | null): ShowCategory {
  const base = CHANNEL_CATEGORY[id] || 'talk'
  if (base === 'news' || base === 'music' || base === 'nature' || base === 'science') return base
  const text = (topic || '').toLowerCase()
  const group = (parent || '').toLowerCase()
  if (base === 'sports') return isVideoGame(text) ? 'gaming' : 'sports'
  if (group === 'sports' || isSportBroadcast(text)) return 'sports'
  if (group === 'music' || /\bmusic\b/.test(text)) return 'music'
  if (group === 'news' || /\b(news|politics)\b/.test(text)) return 'news'
  if (isChatting(text) || group === 'irl') return base === 'sports' ? 'sports' : 'talk'
  if (group === 'games' || text) return 'gaming'
  return base
}

function isChatting(text: string): boolean {
  return /\b(just chatting|irl|special events|talk shows)\b/.test(text)
}

function isVideoGame(text: string): boolean {
  return /\b(fc\s?2\d|fifa|2k|madden|the show|rocket league|nba 2k|ea sports)\b/.test(text)
}

function isSportBroadcast(text: string): boolean {
  if (isVideoGame(text)) return false
  return /\b(sports|soccer|football|basketball|baseball|hockey|nba|nfl|mlb|nhl|ufc|mma|tennis|golf|boxing|cricket|rugby|f1|formula|nascar|indycar|motogp|olympic|athletics|chess|premier league|la liga|bundesliga|wnba|pga|lpga|ipl)\b/.test(text)
}
